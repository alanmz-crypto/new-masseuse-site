#!/usr/bin/env python3
"""Package the frozen image replacements, verified WebP and runtime sources."""
from pathlib import Path
import hashlib
import json
import re
import sys

HERE = Path(__file__).resolve().parent


def build():
    data = json.loads((HERE / 'changes.json').read_text())
    assert set(data['pages']) == {'home', 'therapeutic-massage'}
    assert sum(len(p['pairs']) for p in data['pages'].values()) == 4
    assert len(data['originals']) == 10
    for page in data['pages'].values():
        for pair in page['pairs']:
            body = lambda value: re.sub(r'<img\b[^>]*>', '', re.sub(r'<!--[\s\S]*?-->', '', value))
            assert body(pair['old']) == body(pair['new']), 'E changes only image attributes'
    media = data['media']
    assert (media['width'], media['height'], media['filesize']) == (400, 313, 21796)
    assert media['relative_file'] == '2026/11/therapeutic-red-400.webp'
    assert hashlib.sha256((HERE / 'assets' / media['name']).read_bytes()).hexdigest() == media['sha256']
    media['alt'] = media['title'] = 'The same illustration in red tones.'
    data['new_snippets'] = {}
    for title, filename in [('SiteReviewPerformance', 'performance-runtime.php'), ('SiteReviewEmoji', 'emoji-runtime.php')]:
        code = (HERE / filename).read_text()
        assert code.startswith('<?php\n')
        code = code.removeprefix('<?php\n')
        note = 'Created 2026-11-01 by review-e/install-bundle-e.php; exact rollback snapshot required.'
        data['new_snippets'][title] = {'code': code, 'sha256': hashlib.sha256(code.encode()).hexdigest(), 'note': note, 'meta': {'_wpcode_auto_insert': ['1'], '_wpcode_priority': ['10'], '_wpcode_note': [note], '_wpcode_shortcode_attributes': ['a:0:{}']}}
    return "<?php\n// GENERATED by build-bundle-e.py; exact source and prepared WebP guards.\nreturn json_decode( <<<'BUNDLEEJSON'\n" + json.dumps(data, indent=2, ensure_ascii=False) + "\nBUNDLEEJSON\n, true );\n"


if __name__ == '__main__':
    want = build()
    path = HERE / 'bundle-e-content.php'
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != want:
            sys.exit('Bundle E content stale; run build-bundle-e.py')
        print('Bundle E exact image fragments, WebP SHA and runtime source: PASS')
    else:
        path.write_text(want)
