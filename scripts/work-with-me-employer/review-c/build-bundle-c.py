#!/usr/bin/env python3
"""Package frozen Bundle C fragments/hashes and reviewed runtime sources."""
from pathlib import Path
import hashlib
import json
import sys

HERE = Path(__file__).resolve().parent


def build():
    data = json.loads((HERE / 'changes.json').read_text())
    assert len(data['pages']) == 12
    assert data['heading_count'] == 23 and data['corporate_heading_count'] == 3
    assert data['faq_count'] == 49 and data['approved_mailbox'] == 'butsabad@gmail.com'
    assert sum(p['label'].startswith('semantic H3') for page in data['pages'].values() for p in page['pairs']) == 23
    for page in data['pages'].values():
        for pair in page['pairs']:
            assert pair['old'] and pair['new'] and pair['old'] != pair['new'] and pair['count'] > 0
        assert set(page['hashes']) == {'localhost:8090', 'staging38.thaisolitude.com'}
    for cfg in data['snippets'].values():
        for kind in ['old', 'new']:
            assert hashlib.sha256(cfg[kind].encode()).hexdigest() == cfg[kind + '_sha256']
    assert data['css']['append'].startswith('/* ts-review-c:start')
    assert data['css']['append'].endswith('/* ts-review-c:end */')
    assert (HERE / 'faq-runtime.css').read_text().strip() in data['css']['append']
    data['new_snippets'] = {}
    for title, filename in [('SiteReviewAccessibility', 'accessibility-runtime.php'), ('SiteReviewUtilities', 'site-utilities.php')]:
        code = (HERE / filename).read_text()
        assert code.startswith('<?php\n')
        code = code.removeprefix('<?php\n')
        note = 'Created 2026-11-01 by review-c/install-bundle-c.php; rollback guarded by its exact snapshot.'
        data['new_snippets'][title] = {'code': code, 'sha256': hashlib.sha256(code.encode()).hexdigest(), 'note': note, 'meta': {'_wpcode_auto_insert': ['1'], '_wpcode_priority': ['10'], '_wpcode_note': [note], '_wpcode_shortcode_attributes': ['a:0:{}']}}
    return "<?php\n// GENERATED by build-bundle-c.py; exact captured fragments and reviewed source.\nreturn json_decode( <<<'BUNDLECJSON'\n" + json.dumps(data, indent=2, ensure_ascii=False) + "\nBUNDLECJSON\n, true );\n"


if __name__ == '__main__':
    want = build()
    path = HERE / 'bundle-c-content.php'
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != want:
            sys.exit('Bundle C content stale; run build-bundle-c.py')
        print('Bundle C exact fragments, hashes and runtime sources: PASS')
    else:
        path.write_text(want)
