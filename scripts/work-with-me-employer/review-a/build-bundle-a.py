#!/usr/bin/env python3
"""Package the reviewed exact fragments captured from staging38, with no runtime dependencies.

changes.json records old/new fragments and the frozen jump snippet; bundle-a.css is
an appended, marked CSS block. {{SITE_URL}} is https on staging and production,
and the rehearsal's http://localhost:8090 on its throwaway copy. No attachment IDs
are introduced. The original builders/installers remain historical releases;
roll Bundle A back before using their exact-state rollback checks.
"""
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent


def build():
    data = json.loads((HERE / 'changes.json').read_text())
    assert hashlib.sha256(data['snippet_old'].encode()).hexdigest() == data['snippet_old_sha256']
    for p in data['pairs']:
        assert p['old'] != p['new'] and p['count'] > 0
        # All complete block-attribute objects in both sides must still parse.
        for s in (p['old'], p['new']):
            for m in re.finditer(r'<!-- wp:[\w/-]+ (\{.*?\}) /?-->', s, re.S):
                json.loads(m[1])
    data['css'] = (HERE / 'bundle-a.css').read_text()
    data['snippet_new_sha256'] = hashlib.sha256(data['snippet_new'].encode()).hexdigest()
    # Scan only the new visible wording; unchanged research citations are outside this bundle.
    spec = importlib.util.spec_from_file_location('wording_tiers', HERE / '../client-pages/wording_tiers.py')
    wt = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(wt)
    new_copy = ' '.join([
        'Next step. Corporate and group massage bookings begin November 14, 2026.',
        'Request a corporate massage quote. Ask a question. Explore services. Learn more.',
        'Read more about chair massage: what it is, what to expect and what the research says.',
        'Request a quote for an employee appreciation day or workplace event.',
        'Right now I offer corporate and group massage only, at suitable Portland venues; '
        'individual appointments at a dedicated Thai Solitude location are planned for summer 2027.',
        'Other services: Thai massage. Therapeutic massage. Deep tissue massage. Chair massage. '
        'Corporate & group massage. Request a quote. Email butsabad@gmail.com.',
    ])
    assert not any(re.search(p, new_copy, re.I) for p in wt.BAD), 'Restricted wording in new copy'
    return "<?php\n// GENERATED by build-bundle-a.py; edit changes.json / bundle-a.css, then rebuild.\nreturn json_decode( <<<'REVIEWAJSON'\n" + json.dumps(data, ensure_ascii=False, indent=2) + "\nREVIEWAJSON\n, true );\n"


if __name__ == '__main__':
    result = build()
    out = HERE / 'bundle-a-content.php'
    if '--check' in sys.argv:
        if not out.exists() or out.read_text() != result:
            sys.exit('Bundle A content is stale; run build-bundle-a.py')
        print('Bundle A exact fragments, block JSON, snippet hash and new wording: PASS')
    else:
        out.write_text(result)
