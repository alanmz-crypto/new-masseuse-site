<?php
/**
 * Winding Willow: ADD one new, UNLISTED page /winding-willow/ ("Massage at Winding Willow"), for ONE site at a time.
 * Ryan, 2026-11-13: "move it to staging so it follows all the rules of thaisolitude.com"; asked and answered the same day: an unlisted page (no menu item, no Services row, no snippet
 * change), the research heading registered in wording_tiers.py, "treatment" reworded; target staging39. Standing rule (2026-10-24): add, never subtract without asking.
 *
 * EVERYTHING HERE IS ADDED; nothing that exists is edited. What it writes (WordPress's own storage, so a SiteGround push carries it; no files, no MU-plugin):
 *   1. a NEW published page /winding-willow/ (posts table), content = winding-willow-content.php (generated by build-winding-willow-page.py; no pictures, no media ids);
 *   2. the theme's own title switched off like the other pages (post meta site-post-title = disabled);
 *   3. SureRank's title and description for it (post meta, through SureRank's own API).
 * No menu, no Services row, no snippet, no CSS, no option. The research panels use the existing slide-open CSS block (ts-research-slide) like the other service pages.
 *
 * Allow-list: localhost:8090 and staging39 only. Live is NOT allowed: it needs Ryan's go, a separate enable-live change and his own run.
 *
 * Modes (first WP-CLI argument; run with --user=1):  <mode> [FILE]
 *   preflight    read-only: ready = no post with the slug and no block id in use; applied = the page exactly as written; CHANGED = anything else (stop)
 *   apply        snapshot, create the page and its two meta fields, read everything back; delete the page again if any read-back differs
 *   rollback     FILE = the before-snapshot: delete the page (only if it is still exactly as written)
 * apply and rollback need WWM_BACKUP_DIR (an existing, writable absolute directory outside the web root).
 */

if ( ! defined( 'ABSPATH' ) || ! class_exists( 'WP_CLI' ) ) {
	exit( 'Run with WP-CLI.' );
}

$home = untrailingslashit( home_url() );
$host = (string) wp_parse_url( $home, PHP_URL_HOST ) . ( wp_parse_url( $home, PHP_URL_PORT ) ? ':' . wp_parse_url( $home, PHP_URL_PORT ) : '' );
if ( ! in_array( $host, array( 'localhost:8090', 'staging39.thaisolitude.com' ), true ) ) {
	WP_CLI::error( 'Refusing to run: ' . $home . ' is not an allowed target (localhost:8090 or staging39 only).' );
}
if ( 'astra' !== get_stylesheet() ) {
	WP_CLI::error( 'Active theme is not Astra.' );
}
if ( ! current_user_can( 'manage_options' ) || ! current_user_can( 'unfiltered_html' ) ) {
	WP_CLI::error( 'Run with --user=1 (an administrator) so WordPress does not filter the saved page.' );
}
if ( ! class_exists( '\SureRank\Inc\API\Post' ) || ! method_exists( '\SureRank\Inc\API\Post', 'update_post_meta_common' ) ) {
	WP_CLI::error( 'SureRank page-level SEO API is not available.' );
}
$args = isset( $args ) && is_array( $args ) ? $args : array();
$mode = $args ? (string) $args[0] : 'preflight';
if ( ! in_array( $mode, array( 'preflight', 'apply', 'rollback' ), true ) ) {
	WP_CLI::error( 'Unknown mode: ' . $mode );
}

// ---- the reviewed content ------------------------------------------------------------------------------------------------------------------------
$data = is_file( __DIR__ . '/winding-willow-content.php' ) ? require __DIR__ . '/winding-willow-content.php' : null;
foreach ( array( 'slug', 'title', 'seo_title', 'seo_desc', 'ids', 'page_content', 'research_heading', 'book_url' ) as $k ) {
	if ( ! is_array( $data ) || empty( $data[ $k ] ) ) {
		WP_CLI::error( 'winding-willow-content.php is missing or incomplete (run build-winding-willow-page.py): ' . $k );
	}
}
$slug    = (string) $data['slug'];
$content = trim( (string) $data['page_content'] );
if ( 'winding-willow' !== $slug || false !== strpos( $content, '{{' ) || false !== stripos( $content, '<img' ) ) {
	WP_CLI::error( 'Internal error: the page content is not what was reviewed.' );
}

// ---- wording checks (the builder ran the same gate; this is the second lock) ------------------------------------------------------------------
$strip = function ( $raw ) {
	return html_entity_decode( wp_strip_all_tags( (string) $raw ), ENT_QUOTES, 'UTF-8' );
};
$voice_claims = function ( $what, $text ) {
	if ( preg_match( '/\b(we|our|us|ours)\b/i', $text ) || preg_match( '/\bstudio\b/i', $text ) || preg_match( '/portland[- ]area|portland metro/i', $text ) ) {
		WP_CLI::error( 'The ' . $what . ' text contains we/our/us, studio or Portland-area, which this site never uses.' );
	}
	if ( preg_match( '/\bheal(s|ed|ers?|ing)?\b/i', $text ) || preg_match( '/cure|\btreat|diagnos|guarantee|detox|inflammation/i', $text ) ) {
		WP_CLI::error( 'The ' . $what . ' text contains a claim verb (heal, cure, treat, diagnose, guarantee, detox, inflammation), which this site never uses in prose.' );
	}
};
$evidence_words = array( 'proof', 'measurable', 'effective', 'pain relief', 'relieve', 'relief', 'pain management', 'sciatica', 'headache', 'chronic', 'adhesion', 'corrective', 'accelerat', 'restore',
	'nervous system', 'circulation', 'anxiety', 'cancer', 'neurological', 'disabilit', 'prevention', 'lasting', 'long-term wellness', 'overall health', 'real results' );
$full_list = function ( $what, $text ) use ( $voice_claims, $evidence_words ) {
	$voice_claims( $what, $text );
	foreach ( $evidence_words as $bad ) {
		if ( false !== stripos( $text, $bad ) ) {
			WP_CLI::error( 'The ' . $what . ' text contains a term this site must not use outside a research section: ' . $bad );
		}
	}
};
$heading = (string) $data['research_heading'];
if ( 1 !== substr_count( $content, '>' . esc_html( $heading ) . '</h2>' ) ) {
	WP_CLI::error( 'The research heading is not on the page exactly once; nothing was changed.' );
}
$cut      = strpos( $content, '>' . esc_html( $heading ) . '</h2>' );
$research = substr( $content, $cut );
$cites    = array();
preg_match_all( '#<cite class="ts-source">.*?</cite>#s', $research, $cites );
$full_list( 'page (before the research section)', $strip( substr( $content, 0, $cut ) ) );
$full_list( 'SEO', $data['seo_title'] . ' ' . $data['seo_desc'] . ' ' . $data['title'] );
$voice_claims( 'research section', $strip( preg_replace( '#<cite class="ts-source">.*?</cite>#s', ' ', $research ) ) );
foreach ( $cites[0] as $c ) {
	if ( preg_match( '/\b(we|our|us|ours)\b/i', $strip( $c ) ) || preg_match( '/\bstudio\b/i', $strip( $c ) ) ) {
		WP_CLI::error( 'A source title contains we/our/us or studio, which this site never uses: ' . $strip( $c ) );
	}
}
if ( 7 !== count( $cites[0] ) || mb_strlen( $data['seo_title'] ) > 60 || mb_strlen( $data['seo_desc'] ) > 160 ) {
	WP_CLI::error( 'Internal error: the source count or the SEO lengths are not what was reviewed.' );
}

// ---- the site as it is ------------------------------------------------------------------------------------------------------------------------------
$read = function () use ( $slug, $content, $data ) {
	$pages = get_posts( array( 'post_type' => 'any', 'name' => $slug, 'post_status' => array( 'publish', 'draft', 'pending', 'private', 'future', 'trash' ), 'numberposts' => -1, 'suppress_filters' => true ) );
	if ( 0 === count( $pages ) ) {
		return array( 'state' => 'ready', 'pages' => $pages );
	}
	$pg  = $pages[0];
	$gen = get_post_meta( $pg->ID, 'surerank_settings_general', true );
	$ok  = 1 === count( $pages ) && 'page' === $pg->post_type && 'publish' === $pg->post_status && trim( (string) $pg->post_content ) === $content && $pg->post_title === $data['title']
		&& 'disabled' === get_post_meta( $pg->ID, 'site-post-title', true )
		&& is_array( $gen ) && ( $gen['page_title'] ?? '' ) === $data['seo_title'] && ( $gen['page_description'] ?? '' ) === $data['seo_desc'];
	return array( 'state' => $ok ? 'applied' : 'CHANGED', 'pages' => $pages );
};
$ids_in_use = function () use ( $data ) {
	global $wpdb;
	$used = array();
	foreach ( $data['ids'] as $id ) {
		if ( (int) $wpdb->get_var( $wpdb->prepare( "SELECT COUNT(*) FROM {$wpdb->posts} WHERE post_type <> 'revision' AND post_content LIKE %s", '%' . $wpdb->esc_like( '"block_id":"' . $id . '"' ) . '%' ) ) > 0 ) {
			$used[] = $id;
		}
	}
	return $used;
};
$now    = $read();
$state  = $now['state'];
$report = sprintf( 'host=%s state=%s posts_with_slug=%d', $home, $state, count( $now['pages'] ) );

if ( 'preflight' === $mode ) {
	if ( 'ready' === $state && $ids_in_use() ) {
		WP_CLI::error( 'Block id(s) already used by another post: ' . implode( ', ', $ids_in_use() ) . '; stop and pick new ids. ' . $report );
	}
	if ( 'CHANGED' === $state ) {
		WP_CLI::error( 'A post with the slug winding-willow exists but is not exactly this page; stop and review. ' . $report );
	}
	WP_CLI::success( 'Preflight passed; nothing changed. ' . $report );
	return;
}

$backup_dir = getenv( 'WWM_BACKUP_DIR' );
if ( ! $backup_dir || '/' !== $backup_dir[0] || ! is_dir( $backup_dir ) || ! is_writable( $backup_dir ) || 0 === strpos( realpath( $backup_dir ), realpath( ABSPATH ) ) ) {
	WP_CLI::error( 'WWM_BACKUP_DIR must be an existing, writable absolute directory outside the web root.' );
}

if ( 'apply' === $mode ) {
	if ( 'CHANGED' === $state ) {
		WP_CLI::error( 'The state is not the reviewed one; nothing was changed. ' . $report );
	}
	if ( 'applied' === $state ) {
		WP_CLI::success( 'Nothing to do: already applied. ' . $report );
		return;
	}
	if ( $ids_in_use() ) {
		WP_CLI::error( 'Block id(s) already used by another post: ' . implode( ', ', $ids_in_use() ) . '; nothing was changed.' );
	}
	$file = rtrim( $backup_dir, '/' ) . '/winding-willow-page-before-' . gmdate( 'Ymd-His' ) . '.json';
	$snap = array( 'created' => gmdate( 'c' ), 'home' => $home, 'page_id' => null, 'content_sha256' => hash( 'sha256', $content ) );
	$save = function ( $snap ) use ( $file ) {
		$ok = false !== file_put_contents( $file, wp_json_encode( $snap ) );
		if ( $ok ) {
			chmod( $file, 0600 );
		}
		return $ok && filesize( $file ) > 0;
	};
	if ( ! $save( $snap ) ) {
		WP_CLI::error( 'Could not write the before-snapshot; nothing was changed.' );
	}
	$page_id = wp_insert_post( wp_slash( array(
		'post_type' => 'page', 'post_status' => 'publish', 'post_title' => $data['title'], 'post_name' => $slug, 'post_content' => $content, 'post_author' => get_current_user_id(),
		'comment_status' => 'closed', 'ping_status' => 'closed',
	) ), true );
	if ( is_wp_error( $page_id ) || ! $page_id ) {
		WP_CLI::error( 'Could not create the page; nothing else was changed.' );
	}
	$snap['page_id'] = (int) $page_id;
	$save( $snap );
	update_post_meta( $page_id, 'site-post-title', 'disabled' );
	\SureRank\Inc\API\Post::update_post_meta_common( $page_id, array( 'page_title' => $data['seo_title'], 'page_description' => $data['seo_desc'] ) );

	$after = $read();
	$path  = wp_parse_url( get_permalink( (int) $page_id ), PHP_URL_PATH );
	if ( 'applied' !== $after['state'] || '/winding-willow/' !== $path ) {
		wp_delete_post( (int) $page_id, true );
		$check = $read();
		WP_CLI::error( 'Read-back differed from what was written (state ' . $after['state'] . ', path ' . $path . '); the page was deleted again (state now: ' . $check['state'] . ').' );
	}
	WP_CLI::success( 'Added page #' . $page_id . ' /winding-willow/ (unlisted: no menu, Services or snippet change). Before-snapshot: ' . $file );
	return;
}

// ---- rollback FILE ---------------------------------------------------------------------------------------------------------
$file = isset( $args[1] ) ? (string) $args[1] : '';
$snap = $file && is_file( $file ) ? json_decode( (string) file_get_contents( $file ), true ) : null;
if ( ! is_array( $snap ) || ( $snap['home'] ?? '' ) !== $home || empty( $snap['page_id'] ) ) {
	WP_CLI::error( 'Snapshot is missing, incomplete (the apply may not have finished), or from another site.' );
}
if ( 'applied' !== $state || (int) $now['pages'][0]->ID !== (int) $snap['page_id'] ) {
	WP_CLI::error( 'The page is not exactly as the apply wrote it (edited since?); nothing was changed. ' . $report );
}
wp_delete_post( (int) $snap['page_id'], true );
$check = $read();
if ( 'ready' !== $check['state'] ) {
	WP_CLI::error( 'The page could not be removed; state: ' . $check['state'] );
}
WP_CLI::success( 'Rolled back: page #' . (int) $snap['page_id'] . ' /winding-willow/ deleted; the site is as before the apply.' );

