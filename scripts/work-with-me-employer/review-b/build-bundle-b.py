#!/usr/bin/env python3
"""Package the exact captured Bundle B values and approved wording."""
from pathlib import Path
import hashlib
import importlib.util
import json
import re
import sys

HERE = Path(__file__).resolve().parent


def build():
    data = json.loads((HERE / 'changes.json').read_text())
    for kind in ['old', 'new']:
        assert hashlib.sha256(data['snippet_' + kind].encode()).hexdigest() == data['snippet_' + kind + '_sha256']
    spec = importlib.util.spec_from_file_location('wording_tiers', HERE / '../client-pages/wording_tiers.py')
    wt = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(wt)
    copy = [data['tagline_new'], data['home_new']]
    for p in data['general']:
        copy.extend(p['patch'].values())
        assert len(p['patch'].get('page_title', '')) <= 60
        # The exact approved Corporate sentence is 162; all other descriptions <=160.
        assert len(p['patch'].get('page_description', '')) <= (162 if p['slug'] == 'corporate-massage-portland' else 160)
    assert not any(re.search(pattern, ' '.join(copy), re.I) for pattern in wt.BAD)
    return "<?php\n// GENERATED by build-bundle-b.py from captured values and approved copy.\nreturn json_decode( <<<'BUNDLEBJSON'\n" + json.dumps(data, indent=2, ensure_ascii=False) + "\nBUNDLEBJSON\n, true );\n"


if __name__ == '__main__':
    text = build()
    out = HERE / 'bundle-b-content.php'
    if '--check' in sys.argv:
        if not out.exists() or out.read_text() != text:
            sys.exit('Bundle B content stale; run build-bundle-b.py')
        print('Bundle B source hashes, approved wording and package: PASS')
    else:
        out.write_text(text)
