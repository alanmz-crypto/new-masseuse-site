#!/usr/bin/env python3
"""Booking date moves from November 1 to November 14, 2026 (Ryan, 2026-10-30: "Change booking begins to Nov 14th. Everywhere.").
Reads the reviewed availability update (../availability/availability-content.php: what is live now) and writes booking-date-content.php:
every text that says corporate/group bookings begin "November 1, 2026" becomes the same text with "November 14, 2026", and the announcement strip's code
(WPCode snippet "CorporateBand") flips on 2026-11-14 00:00 Pacific instead of 2026-11-01 and says the new date before then.
NOT changed on purpose: the employment dates on Work With Me ("Start - From November 1", "in person from November 1"): they are about her employment start, not client bookings (Ryan to confirm).
Run: python3 build-booking-date.py   (writes booking-date-content.php next to this file; --check compares the file on disk with a fresh build)"""
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "availability", "availability-content.php"), encoding="utf-8").read()
av = json.loads(src.split("<<<'AVJSON'\n")[1].split("\nAVJSON")[0])

OLD_D, NEW_D = "November 1, 2026", "November 14, 2026"
pairs = []
for p in av["pairs"]:
    if OLD_D not in p["new"]:
        continue
    assert p["new"].count(OLD_D) == 1, p["label"]
    pairs.append({"slug": p["slug"], "label": p["label"].replace("Work With Me:", "Work With Me:") + " (booking date)", "old": p["new"], "new": p["new"].replace(OLD_D, NEW_D)})
assert len(pairs) == 8, len(pairs)

band_old = av["band_new"]
band_new = band_old
for a, b in (("'2026-11-01 00:00:00'", "'2026-11-14 00:00:00'"), ("bookings on " + OLD_D, "bookings on " + NEW_D), ("Before " + OLD_D + " (Pacific time)", "Before " + NEW_D + " (Pacific time)")):
    assert band_new.count(a) == 1, a
    band_new = band_new.replace(a, b)
assert "2026-11-01" not in band_new and OLD_D not in band_new

out = {"band_old": band_old, "band_new": band_new, "band_title": av["band_title"], "pairs": pairs}
text = ("<?php\n// GENERATED by build-booking-date.py: do not edit by hand (edit the builder and run it again). install-booking-date.php loads this.\n"
        "return json_decode( <<<'AVJSON'\n" + json.dumps(out, indent=1, ensure_ascii=False) + "\nAVJSON\n, true );\n")
path = os.path.join(here, "booking-date-content.php")
if "--check" in sys.argv:
    print("booking-date-content.php matches the builder" if open(path, encoding="utf-8").read() == text else "DIFFERENT: run build-booking-date.py")
    sys.exit(0 if open(path, encoding="utf-8").read() == text else 1)
open(path, "w", encoding="utf-8").write(text)
print("wrote", path, "-", len(pairs), "replacements + the strip code")
