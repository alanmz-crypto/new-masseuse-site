#!/usr/bin/env python3
"""Build sandwich-update-content.php: the exact old and new research-section text that install-sandwich-update.php swaps on the Thai Massage (ID 1160) and Therapeutic Massage (ID 1107) pages. Standard library only.

    python3 -I -B scripts/work-with-me-employer/evidence-update/build-sandwich-update.py          write sandwich-update-content.php next to this file
    python3 -I -B scripts/work-with-me-employer/evidence-update/build-sandwich-update.py --check  exit 1 if that file is not what this script produces

WHY AN UPDATE and not a re-run of the original installers: both pages are already LIVE with their first research sections (version 1, frozen here as thai-research-v1.html and therapeutic-research-v1.html: the exact text now on live).
Ryan, 2026-10-19: "would you double check on both of the pages we just researched to make sure I didn't miss any discouraging or poor results ... so we can sandwich the discouraging results between two assertive
positive claims" and "you can sandwich with the method you used on the Therapeutic page. That worked well." The audit found results the pages lacked (a systematic review of massage adverse events, a Thai-massage case
report of a serious injury and a commentary on possible adverse effects, a null shoulder-strength result, trials where placebo or sham massage did as well, or where massage lowered muscle activity and vigor, and some
favorable results such as a soccer-player trial) and the panels were rewritten so each runs: what the studies found in massage's favor, then the weaker, mixed and negative results in full, then an encouraging close.
Everything above the research heading (the body, the FAQ, the heritage line, the pictures) is untouched: the update replaces only the text from the research heading to the end of the page, so the first-use order of
the numbered markers above it cannot change. The builders (../thai/build-thai-evidence.py, ../therapeutic/build-therapeutic-evidence.py) hold the new text; this file only pairs it with the frozen old text.
"""
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'sandwich-update-content.php')


def load(name, rel):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, rel))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def research_part(sections, start):
    i = sections.index(start)
    return sections[i:]


def build():
    pages = []
    for slug, label, builder, old_file in (('thai-massage', 'Thai Massage', '../thai/build-thai-evidence.py', 'thai-research-v1.html'),
                                           ('therapeutic-massage', 'Therapeutic Massage', '../therapeutic/build-therapeutic-evidence.py', 'therapeutic-research-v1.html')):
        d = load('b_' + slug.replace('-', '_'), builder).build()
        old = open(os.path.join(HERE, old_file), encoding='utf-8').read()
        new = research_part(d['sections'], d['research_start'])
        if old == new:
            raise SystemExit('the new research text for %s equals the frozen old text: nothing to update' % slug)
        if not old.startswith(d['research_start']):
            raise SystemExit('the frozen old text for %s does not start with the research heading' % slug)
        pages.append({'slug': slug, 'label': label, 'old_research': old, 'new_research': new, 'research_start': d['research_start'], 'source_count': d['source_count'],
                      'heading': 'What the Research Says About %s' % label})
    return {'pages': pages}


def php(data):
    js = json.dumps(data, ensure_ascii=False, indent=1)
    assert 'SANDWICHJSON' not in js
    return ('<?php\n// GENERATED by build-sandwich-update.py: do not edit by hand (edit the builders and run it again). install-sandwich-update.php loads this.\n'
            'return json_decode( <<<\'SANDWICHJSON\'\n%s\nSANDWICHJSON\n, true );\n') % js


if __name__ == '__main__':
    body = php(build())
    if '--check' in sys.argv:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        print('sandwich-update-content.php matches the builders' if have == body else 'sandwich-update-content.php is OUT OF DATE: run the builder')
        sys.exit(0 if have == body else 1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(body)
    print('wrote %s (%d bytes)' % (OUT, len(body.encode('utf-8'))))

