$snippet_state = function ( $found, $sha_old, $old, $new ) {
	if ( 1 !== count( $found ) || 'publish' !== $found[0]->post_status ) {
		return 'CHANGED';
	}
	$code = (string) $found[0]->post_content;
	if ( hash( 'sha256', $code ) === $sha_old && 1 === substr_count( $code, $old ) && 0 === substr_count( $code, $new ) ) {
		return 'ready';
	}
	if ( 1 === substr_count( $code, $new ) && hash( 'sha256', str_replace( $new, $old, $code ) ) === $sha_old ) {   // applied = the frozen code with exactly the insertion
		return 'applied';
	}
	return 'CHANGED';
};

