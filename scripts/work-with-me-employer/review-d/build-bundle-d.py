#!/usr/bin/env python3
"""Package reviewed exact fragments and guards; no site access or mutation."""
from pathlib import Path
import hashlib
import json
import sys

HERE = Path(__file__).resolve().parent


def build():
    data = json.loads((HERE / 'changes.json').read_text())
    assert len(data['pages']) == 9
    assert sum(len(p['pairs']) for p in data['pages'].values()) == 45
    assert set(data['snippets']) == {'A11yHeartLinks'}
    for page in data['pages'].values():
        for pair in page['pairs']:
            assert pair['old'] and pair['old'] != pair['new'] and pair['count'] > 0
        assert set(page['hashes']) == {'localhost:8090', 'staging38.thaisolitude.com', 'thaisolitude.com'}
        for hashes in page['hashes'].values():
            assert set(hashes) == {'old', 'new'} and hashes['old'] != hashes['new']
    for snippet in data['snippets'].values():
        for kind in ['old', 'new']:
            assert hashlib.sha256(snippet[kind].encode()).hexdigest() == snippet[kind + '_sha256']
    assert data['astra_footer_key'] == 'footer-copyright-editor'
    assert data['astra_footer_old'].replace('LMT - Oregon', 'LMT &middot; Oregon') == data['astra_footer_new']
    return "<?php\n// GENERATED by build-bundle-d.py; reviewed exact captured fragments.\nreturn json_decode( <<<'BUNDLEDJSON'\n" + json.dumps(data, indent=2, ensure_ascii=False) + "\nBUNDLEDJSON\n, true );\n"


if __name__ == '__main__':
    want = build()
    path = HERE / 'bundle-d-content.php'
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != want:
            sys.exit('Bundle D content stale; run build-bundle-d.py')
        print('Bundle D exact fragments, hashes and snippet source: PASS')
    else:
        path.write_text(want)
